DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM project p
    JOIN finance_folder_context c ON c.project_id = p.id
  ) THEN
    RAISE EXCEPTION 'FINANCE_PROJECT_NOT_FOUND';
  END IF;
END $$;

INSERT INTO folder (id, name, "projectId", "parentFolderId", "createdAt", "updatedAt") VALUES
